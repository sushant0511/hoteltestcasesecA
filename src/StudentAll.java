
public class StudentAll {

	int id;
	String name;
	float fees;
	public StudentAll(int id, String name, float fees) {
		super();
		this.id = id;
		this.name = name;
		this.fees = fees;
	}
	@Override
	public String toString() {
		return "StudentAll [id=" + id + ", name=" + name + ", fees=" + fees + "]";
	}
	
	
	
	
}
